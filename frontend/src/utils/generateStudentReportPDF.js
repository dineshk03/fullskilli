import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

/**
 * Generate individual student performance PDF report
 * @param {Object} studentData - Complete student data with performance metrics
 * @param {string} adminName - Name of the admin generating the report
 */
export const generateStudentReportPDF = (studentData, adminName = "Administrator") => {
  try {
    const doc = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4'
    });
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    let yPosition = 15;

    // Color palette
    const primaryColor = [59, 130, 246]; // Blue
    const accentColor = [16, 185, 129]; // Green
    const warningColor = [245, 158, 11]; // Orange
    const dangerColor = [239, 68, 68]; // Red
    const darkText = [15, 23, 42];
    const lightText = [100, 116, 139];

    // ===== HEADER SECTION =====
    doc.setFillColor(...primaryColor);
    doc.rect(0, 0, pageWidth, 45, 'F');

    // Header gradient effect
    for (let i = 0; i < 5; i++) {
      doc.setFillColor(59 + i * 10, 130 + i * 5, 246 - i * 10);
      doc.rect(0, i * 2, pageWidth, 2, 'F');
    }

    // Header text
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(24);
    doc.setFont(undefined, 'bold');
    doc.text('STUDENT PERFORMANCE REPORT', 15, 20);
    doc.setFontSize(11);
    doc.setFont(undefined, 'normal');
    doc.text(`Generated by: ${adminName}`, 15, 30);
    doc.text(`Date: ${new Date().toLocaleDateString('en-IN')}`, 15, 37);
    yPosition = 55;

    // ===== STUDENT INFO SECTION =====
    doc.setTextColor(...darkText);
    doc.setFontSize(18);
    doc.setFont(undefined, 'bold');
    doc.text('Student Information', 15, yPosition);
    yPosition += 10;

    // Student details box
    doc.setFillColor(248, 250, 252);
    doc.rect(15, yPosition, pageWidth - 30, 35, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.rect(15, yPosition, pageWidth - 30, 35, 'S');
    doc.setFontSize(12);
    doc.setFont(undefined, 'bold');
    doc.setTextColor(...darkText);
    doc.text('Name:', 20, yPosition + 10);
    doc.setFont(undefined, 'normal');
    doc.text(studentData.name || 'N/A', 45, yPosition + 10);
    doc.setFont(undefined, 'bold');
    doc.text('Email:', 20, yPosition + 20);
    doc.setFont(undefined, 'normal');
    doc.text(studentData.email || 'N/A', 45, yPosition + 20);
    doc.setFont(undefined, 'bold');
    doc.text('Performance Level:', 20, yPosition + 30);
    doc.setFont(undefined, 'normal');

    // Color code performance level
    const performanceColors = {
      'Excellent': accentColor,
      'Good': primaryColor,
      'Average': [245, 158, 11],
      'Below Average': warningColor,
      'Poor': dangerColor
    };
    doc.setTextColor(...(performanceColors[studentData.performanceLevel] || lightText));
    doc.text(studentData.performanceLevel || 'N/A', 70, yPosition + 30);
    yPosition += 50;

    // ===== PERFORMANCE SUMMARY =====
    doc.setTextColor(...darkText);
    doc.setFontSize(16);
    doc.setFont(undefined, 'bold');
    doc.text('Performance Summary', 15, yPosition);
    yPosition += 15;

    // Performance metrics cards
    const metrics = [{
      label: 'Average Score',
      value: `${studentData.averageScore?.toFixed(1) || 0}%`,
      color: primaryColor
    }, {
      label: 'Total Attempts',
      value: studentData.totalAttempts || 0,
      color: accentColor
    }, {
      label: 'Success Rate',
      value: `${studentData.completionRate?.toFixed(1) || 0}%`,
      color: primaryColor
    }, {
      label: 'Courses Enrolled',
      value: studentData.courses?.length || 0,
      color: warningColor
    }];
    const cardWidth = (pageWidth - 50) / 2;
    const cardHeight = 25;
    metrics.forEach((metric, index) => {
      const x = 15 + index % 2 * (cardWidth + 10);
      const y = yPosition + Math.floor(index / 2) * (cardHeight + 10);

      // Card background
      doc.setFillColor(248, 250, 252);
      doc.rect(x, y, cardWidth, cardHeight, 'F');
      doc.setDrawColor(...metric.color);
      doc.setLineWidth(0.5);
      doc.rect(x, y, cardWidth, cardHeight, 'S');

      // Metric text
      doc.setFontSize(10);
      doc.setFont(undefined, 'bold');
      doc.setTextColor(...lightText);
      doc.text(metric.label, x + 5, y + 8);
      doc.setFontSize(14);
      doc.setFont(undefined, 'bold');
      doc.setTextColor(...metric.color);
      doc.text(String(metric.value), x + 5, y + 18);
    });
    yPosition += 70;

    // ===== QUIZ PERFORMANCE DETAILS =====
    if (studentData.quizzes && studentData.quizzes.length > 0) {
      doc.setTextColor(...darkText);
      doc.setFontSize(16);
      doc.setFont(undefined, 'bold');
      doc.text('Quiz Performance Details', 15, yPosition);
      yPosition += 10;

      // Prepare quiz data for table
      const quizTableData = studentData.quizzes.map(quiz => [quiz.quizTitle || 'Quiz', quiz.courseName || 'N/A', quiz.attempts || 0, quiz.passed || 0, quiz.failed || 0, `${quiz.averageScore?.toFixed(1) || 0}%`]);

      // Quiz performance table
      autoTable(doc, {
        startY: yPosition,
        head: [['Quiz Title', 'Course', 'Attempts', 'Passed', 'Failed', 'Avg Score']],
        body: quizTableData,
        theme: 'grid',
        headStyles: {
          fillColor: primaryColor,
          textColor: [255, 255, 255],
          fontSize: 10,
          fontStyle: 'bold'
        },
        bodyStyles: {
          fontSize: 9,
          textColor: darkText
        },
        alternateRowStyles: {
          fillColor: [248, 250, 252]
        },
        columnStyles: {
          0: {
            cellWidth: 45
          },
          1: {
            cellWidth: 35
          },
          2: {
            cellWidth: 20,
            halign: 'center'
          },
          3: {
            cellWidth: 20,
            halign: 'center'
          },
          4: {
            cellWidth: 20,
            halign: 'center'
          },
          5: {
            cellWidth: 25,
            halign: 'center'
          }
        },
        margin: {
          left: 15,
          right: 15
        }
      });
      yPosition = doc.lastAutoTable.finalY + 20;
    }

    // ===== PERFORMANCE ANALYSIS =====
    if (yPosition > pageHeight - 80) {
      doc.addPage();
      yPosition = 20;
    }
    doc.setTextColor(...darkText);
    doc.setFontSize(16);
    doc.setFont(undefined, 'bold');
    doc.text('Performance Analysis & Recommendations', 15, yPosition);
    yPosition += 15;

    // Generate recommendations based on performance
    const recommendations = generateStudentRecommendations(studentData);
    recommendations.forEach(recommendation => {
      if (yPosition > pageHeight - 30) {
        doc.addPage();
        yPosition = 20;
      }

      // Recommendation box
      const boxHeight = 25;
      const priorityColors = {
        'high': dangerColor,
        'medium': warningColor,
        'low': accentColor
      };
      doc.setFillColor(...(priorityColors[recommendation.priority] || lightText));
      doc.rect(15, yPosition, 5, boxHeight, 'F');
      doc.setFillColor(248, 250, 252);
      doc.rect(20, yPosition, pageWidth - 35, boxHeight, 'F');
      doc.setDrawColor(226, 232, 240);
      doc.rect(20, yPosition, pageWidth - 35, boxHeight, 'S');

      // Recommendation text
      doc.setFontSize(11);
      doc.setFont(undefined, 'bold');
      doc.setTextColor(...darkText);
      doc.text(recommendation.title, 25, yPosition + 8);
      doc.setFontSize(9);
      doc.setFont(undefined, 'normal');
      doc.setTextColor(...lightText);

      // Split long text into multiple lines
      const splitText = doc.splitTextToSize(recommendation.description, pageWidth - 50);
      doc.text(splitText, 25, yPosition + 15);
      yPosition += boxHeight + 10;
    });

    // ===== FOOTER =====
    const pageCount = doc.internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);

      // Footer line
      doc.setDrawColor(...lightText);
      doc.setLineWidth(0.5);
      doc.line(15, pageHeight - 20, pageWidth - 15, pageHeight - 20);

      // Footer text
      doc.setFontSize(8);
      doc.setTextColor(...lightText);
      doc.setFont(undefined, 'normal');
      doc.text('Student Performance Report - Confidential', 15, pageHeight - 12);
      doc.text(`Page ${i} of ${pageCount}`, pageWidth - 15, pageHeight - 12, {
        align: 'right'
      });
      doc.setFontSize(7);
      doc.text(`Generated on ${new Date().toLocaleDateString('en-IN')} by Learning Management System`, pageWidth / 2, pageHeight - 6, {
        align: 'center'
      });
    }

    // Save the PDF
    const filename = `student-report-${studentData.name?.replace(/\s+/g, '-').toLowerCase() || 'student'}-${new Date().toISOString().slice(0, 10)}.pdf`;
    doc.save(filename);
    return true;
  } catch (error) {
    console.error('Error generating student report PDF:', error);
    throw error;
  }
};

// Generate recommendations based on student performance
function generateStudentRecommendations(studentData) {
  const recommendations = [];

  // Performance-based recommendations
  if (studentData.averageScore < 60) {
    recommendations.push({
      priority: 'high',
      title: 'Immediate Academic Support Required',
      description: `With an average score of ${studentData.averageScore?.toFixed(1)}%, this student needs immediate academic intervention. Consider providing additional study materials, one-on-one tutoring sessions, or remedial classes to improve understanding of core concepts.`
    });
  } else if (studentData.averageScore < 75) {
    recommendations.push({
      priority: 'medium',
      title: 'Additional Practice Recommended',
      description: `The student shows moderate performance with ${studentData.averageScore?.toFixed(1)}% average score. Recommend additional practice exercises and review sessions to strengthen weak areas and improve overall performance.`
    });
  } else if (studentData.averageScore >= 90) {
    recommendations.push({
      priority: 'low',
      title: 'Excellent Performance - Consider Advanced Challenges',
      description: `Outstanding performance with ${studentData.averageScore?.toFixed(1)}% average score! Consider providing advanced challenges, leadership opportunities, or mentoring roles to keep this student engaged and motivated.`
    });
  }

  // Completion rate recommendations
  if (studentData.completionRate < 70) {
    recommendations.push({
      priority: 'high',
      title: 'Low Completion Rate Needs Attention',
      description: `With only ${studentData.completionRate?.toFixed(1)}% completion rate, the student may be struggling with time management or course difficulty. Consider flexible deadlines, study schedule planning, or motivational support.`
    });
  }

  // Attempt pattern recommendations
  if (studentData.totalAttempts > studentData.totalQuizzes * 2) {
    recommendations.push({
      priority: 'medium',
      title: 'Multiple Attempts Pattern Detected',
      description: `The student is taking multiple attempts per quiz (${(studentData.totalAttempts / studentData.totalQuizzes).toFixed(1)} attempts per quiz on average). This may indicate difficulty with material comprehension. Consider providing study guides before quiz attempts.`
    });
  }

  // Course engagement recommendations
  if (studentData.courses && studentData.courses.length < 2) {
    recommendations.push({
      priority: 'low',
      title: 'Limited Course Engagement',
      description: `The student is enrolled in only ${studentData.courses.length} course(s). Consider encouraging enrollment in additional relevant courses to broaden knowledge and improve overall academic engagement.`
    });
  }

  // Default recommendation if no specific issues
  if (recommendations.length === 0) {
    recommendations.push({
      priority: 'low',
      title: 'Maintain Current Performance',
      description: `The student shows consistent performance across all metrics. Continue with current study patterns and consider setting new academic goals to maintain motivation and growth.`
    });
  }
  return recommendations;
}
