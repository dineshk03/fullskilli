import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

/**
 * Generate comprehensive admin quiz analytics PDF report
 * @param {Object} analyticsData - Complete analytics data from admin dashboard
 * @param {Object} filters - Applied filters (timeRange, courseId, etc.)
 * @param {string} adminName - Name of the admin generating the report
 * @param {string} reportType - Type of report (overview, detailed, comparison)
 */
export const generateAdminQuizReportPDF = (analyticsData, filters = {}, adminName = "Administrator", reportType = "overview") => {
  try {
    const doc = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4'
    });
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    let yPosition = 15;

    // Modern Color Palette for Admin Reports
    const primaryColor = [59, 130, 246]; // Blue
    const accentColor = [16, 185, 129]; // Green
    const warningColor = [245, 158, 11]; // Orange
    const dangerColor = [239, 68, 68]; // Red
    const darkText = [15, 23, 42];
    const lightText = [100, 116, 139];
    const lightBg = [248, 250, 252];
    const borderColor = [226, 232, 240];

    // ===== HEADER SECTION =====
    doc.setFillColor(...primaryColor);
    doc.rect(0, 0, pageWidth, 45, 'F');

    // Header gradient effect (simulated with multiple rectangles)
    for (let i = 0; i < 5; i++) {
      doc.setFillColor(59 + i * 10, 130 + i * 5, 246 - i * 10);
      doc.rect(0, i * 2, pageWidth, 2, 'F');
    }

    // Header text
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(24);
    doc.setFont(undefined, 'bold');
    doc.text('QUIZ ANALYTICS REPORT', 15, 20);
    doc.setFontSize(11);
    doc.setFont(undefined, 'normal');
    doc.text('Administrative Dashboard Analytics', 15, 30);

    // Report metadata
    doc.setFontSize(9);
    doc.text(`Generated by: ${adminName}`, pageWidth - 15, 20, {
      align: 'right'
    });
    doc.text(`Date: ${new Date().toLocaleDateString('en-IN')}`, pageWidth - 15, 26, {
      align: 'right'
    });
    doc.text(`Time: ${new Date().toLocaleTimeString('en-IN')}`, pageWidth - 15, 32, {
      align: 'right'
    });
    yPosition = 55;

    // ===== EXECUTIVE SUMMARY SECTION =====
    doc.setFillColor(...lightBg);
    doc.rect(15, yPosition, pageWidth - 30, 50, 'F');
    doc.setDrawColor(...borderColor);
    doc.setLineWidth(1);
    doc.rect(15, yPosition, pageWidth - 30, 50, 'S');

    // Accent border
    doc.setDrawColor(...primaryColor);
    doc.setLineWidth(3);
    doc.line(15, yPosition, 15, yPosition + 50);
    doc.setTextColor(...darkText);
    doc.setFontSize(14);
    doc.setFont(undefined, 'bold');
    doc.text('Executive Summary', 20, yPosition + 10);
    yPosition += 18;

    // Summary metrics
    const summary = analyticsData?.summary || {};
    doc.setFontSize(10);
    doc.setFont(undefined, 'normal');
    const summaryData = [{
      label: 'Total Quiz Attempts:',
      value: summary.totalAttempts?.toLocaleString() || '0',
      color: primaryColor
    }, {
      label: 'Unique Students:',
      value: summary.uniqueStudents?.toLocaleString() || '0',
      color: accentColor
    }, {
      label: 'Overall Pass Rate:',
      value: `${(summary.passRate || 0).toFixed(1)}%`,
      color: summary.passRate >= 70 ? accentColor : warningColor
    }, {
      label: 'Average Score:',
      value: `${(summary.averageScore || 0).toFixed(1)}%`,
      color: summary.averageScore >= 80 ? accentColor : summary.averageScore >= 60 ? warningColor : dangerColor
    }];
    summaryData.forEach((item, index) => {
      const xPos = 20 + index % 2 * 85;
      const yPos = yPosition + Math.floor(index / 2) * 12;
      doc.setTextColor(...lightText);
      doc.text(item.label, xPos, yPos);
      doc.setTextColor(...item.color);
      doc.setFont(undefined, 'bold');
      doc.text(item.value, xPos + 60, yPos);
      doc.setFont(undefined, 'normal');
    });
    yPosition += 45;

    // ===== FILTER INFORMATION =====
    if (Object.keys(filters).length > 0) {
      doc.setTextColor(...darkText);
      doc.setFontSize(11);
      doc.setFont(undefined, 'bold');
      doc.text('Report Filters Applied:', 15, yPosition);
      yPosition += 8;
      doc.setFontSize(9);
      doc.setFont(undefined, 'normal');
      doc.setTextColor(...lightText);
      const filterText = [];
      if (filters.timeRange) filterText.push(`Time Range: Last ${filters.timeRange} days`);
      if (filters.courseId) filterText.push(`Course Filter: Applied`);
      if (filters.quizId) filterText.push(`Quiz Filter: Applied`);
      doc.text(filterText.join(' | '), 15, yPosition);
      yPosition += 15;
    }

    // ===== PERFORMANCE ANALYTICS SECTION =====
    doc.setTextColor(...darkText);
    doc.setFontSize(14);
    doc.setFont(undefined, 'bold');
    doc.text('Performance Analytics', 15, yPosition);
    yPosition += 10;

    // Score Distribution Analysis
    if (analyticsData?.scoreDistribution?.length > 0) {
      doc.setFontSize(11);
      doc.setFont(undefined, 'bold');
      doc.text('Score Distribution Analysis', 15, yPosition);
      yPosition += 8;
      const scoreRanges = ['0-20%', '21-40%', '41-60%', '61-80%', '81-100%'];
      const colors = [dangerColor, warningColor, [245, 158, 11], accentColor, [34, 197, 94]];

      // Create visual bars for score distribution
      analyticsData.scoreDistribution.forEach((bucket, index) => {
        const total = analyticsData.scoreDistribution.reduce((sum, b) => sum + b.count, 0);
        const percentage = total > 0 ? bucket.count / total * 100 : 0;
        const barWidth = percentage / 100 * 120;

        // Range label
        doc.setFontSize(9);
        doc.setTextColor(...darkText);
        doc.text(scoreRanges[index], 15, yPosition);

        // Background bar
        doc.setFillColor(240, 240, 240);
        doc.rect(45, yPosition - 4, 120, 6, 'F');

        // Filled bar
        doc.setFillColor(...colors[index]);
        doc.rect(45, yPosition - 4, barWidth, 6, 'F');

        // Count and percentage
        doc.setTextColor(...darkText);
        doc.text(`${bucket.count} (${percentage.toFixed(1)}%)`, 170, yPosition);
        yPosition += 10;
      });
      yPosition += 5;
    }

    // ===== TOP PERFORMING QUIZZES TABLE =====
    if (analyticsData?.quizPerformance?.length > 0) {
      if (yPosition > pageHeight - 80) {
        doc.addPage();
        yPosition = 15;
      }
      doc.setTextColor(...darkText);
      doc.setFontSize(11);
      doc.setFont(undefined, 'bold');
      doc.text('Quiz Performance Overview', 15, yPosition);
      yPosition += 8;
      const quizTableData = analyticsData.quizPerformance.slice(0, 10).map(quiz => [quiz.quizTitle || 'Unknown Quiz', quiz.totalAttempts || 0, quiz.uniqueStudents || 0, `${(quiz.passRate || 0).toFixed(1)}%`, `${(quiz.averageScore || 0).toFixed(1)}%`, quiz.difficultyScore >= 50 ? 'Hard' : quiz.difficultyScore >= 30 ? 'Medium' : 'Easy']);
      autoTable(doc, {
        startY: yPosition,
        head: [['Quiz Title', 'Attempts', 'Students', 'Pass Rate', 'Avg Score', 'Difficulty']],
        body: quizTableData,
        theme: 'grid',
        headStyles: {
          fillColor: primaryColor,
          textColor: [255, 255, 255],
          fontStyle: 'bold',
          fontSize: 9,
          halign: 'center'
        },
        bodyStyles: {
          fontSize: 8,
          textColor: darkText
        },
        alternateRowStyles: {
          fillColor: lightBg
        },
        columnStyles: {
          0: {
            cellWidth: 60,
            halign: 'left'
          },
          1: {
            cellWidth: 20,
            halign: 'center'
          },
          2: {
            cellWidth: 20,
            halign: 'center'
          },
          3: {
            cellWidth: 25,
            halign: 'center'
          },
          4: {
            cellWidth: 25,
            halign: 'center'
          },
          5: {
            cellWidth: 25,
            halign: 'center'
          }
        },
        margin: {
          left: 15,
          right: 15
        }
      });
      yPosition = doc.lastAutoTable.finalY + 15;
    }

    // ===== STUDENT INSIGHTS SECTION =====
    if (analyticsData?.studentInsights) {
      if (yPosition > pageHeight - 100) {
        doc.addPage();
        yPosition = 15;
      }
      doc.setTextColor(...darkText);
      doc.setFontSize(14);
      doc.setFont(undefined, 'bold');
      doc.text('Student Performance Insights', 15, yPosition);
      yPosition += 15;

      // Top Performers
      if (analyticsData.studentInsights.topPerformers?.length > 0) {
        doc.setFontSize(11);
        doc.setFont(undefined, 'bold');
        doc.text('Top Performers', 15, yPosition);
        yPosition += 8;
        const topPerformersData = analyticsData.studentInsights.topPerformers.slice(0, 5).map(student => [student.studentName || 'Unknown Student', student.totalAttempts || 0, `${(student.passRate || 0).toFixed(1)}%`, `${(student.averageScore || 0).toFixed(1)}%`, student.performanceLevel || 'Unknown']);
        autoTable(doc, {
          startY: yPosition,
          head: [['Student Name', 'Attempts', 'Pass Rate', 'Avg Score', 'Level']],
          body: topPerformersData,
          theme: 'striped',
          headStyles: {
            fillColor: accentColor,
            textColor: [255, 255, 255],
            fontStyle: 'bold',
            fontSize: 9
          },
          bodyStyles: {
            fontSize: 8,
            textColor: darkText
          },
          columnStyles: {
            0: {
              cellWidth: 70
            },
            1: {
              cellWidth: 25,
              halign: 'center'
            },
            2: {
              cellWidth: 25,
              halign: 'center'
            },
            3: {
              cellWidth: 25,
              halign: 'center'
            },
            4: {
              cellWidth: 30,
              halign: 'center'
            }
          },
          margin: {
            left: 15,
            right: 15
          }
        });
        yPosition = doc.lastAutoTable.finalY + 10;
      }

      // Students Needing Attention
      if (analyticsData.studentInsights.strugglingStudents?.length > 0) {
        if (yPosition > pageHeight - 60) {
          doc.addPage();
          yPosition = 15;
        }
        doc.setFontSize(11);
        doc.setFont(undefined, 'bold');
        doc.setTextColor(...dangerColor);
        doc.text('Students Needing Attention', 15, yPosition);
        yPosition += 8;
        const strugglingData = analyticsData.studentInsights.strugglingStudents.slice(0, 5).map(student => [student.studentName || 'Unknown Student', student.totalAttempts || 0, `${(student.passRate || 0).toFixed(1)}%`, `${(student.averageScore || 0).toFixed(1)}%`, student.performanceLevel || 'Unknown']);
        autoTable(doc, {
          startY: yPosition,
          head: [['Student Name', 'Attempts', 'Pass Rate', 'Avg Score', 'Level']],
          body: strugglingData,
          theme: 'striped',
          headStyles: {
            fillColor: dangerColor,
            textColor: [255, 255, 255],
            fontStyle: 'bold',
            fontSize: 9
          },
          bodyStyles: {
            fontSize: 8,
            textColor: darkText
          },
          columnStyles: {
            0: {
              cellWidth: 70
            },
            1: {
              cellWidth: 25,
              halign: 'center'
            },
            2: {
              cellWidth: 25,
              halign: 'center'
            },
            3: {
              cellWidth: 25,
              halign: 'center'
            },
            4: {
              cellWidth: 30,
              halign: 'center'
            }
          },
          margin: {
            left: 15,
            right: 15
          }
        });
        yPosition = doc.lastAutoTable.finalY + 15;
      }
    }

    // ===== RECOMMENDATIONS SECTION =====
    if (yPosition > pageHeight - 80) {
      doc.addPage();
      yPosition = 15;
    }
    doc.setTextColor(...darkText);
    doc.setFontSize(14);
    doc.setFont(undefined, 'bold');
    doc.text('Recommendations & Action Items', 15, yPosition);
    yPosition += 15;

    // Generate recommendations based on data
    const recommendations = generateRecommendations(analyticsData);
    recommendations.forEach((rec, index) => {
      // Priority indicator
      const priorityColor = rec.priority === 'high' ? dangerColor : rec.priority === 'medium' ? warningColor : accentColor;
      doc.setFillColor(...priorityColor);
      doc.rect(15, yPosition - 3, 4, 8, 'F');

      // Recommendation text
      doc.setTextColor(...darkText);
      doc.setFontSize(10);
      doc.setFont(undefined, 'bold');
      doc.text(`${index + 1}. ${rec.title}`, 25, yPosition);
      yPosition += 6;
      doc.setFontSize(9);
      doc.setFont(undefined, 'normal');
      doc.setTextColor(...lightText);
      const wrappedText = doc.splitTextToSize(rec.description, pageWidth - 40);
      doc.text(wrappedText, 25, yPosition);
      yPosition += wrappedText.length * 4 + 8;
      if (yPosition > pageHeight - 30) {
        doc.addPage();
        yPosition = 15;
      }
    });

    // ===== FOOTER ON ALL PAGES =====
    const pageCount = doc.internal.pages.length;
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      const finalPageHeight = doc.internal.pageSize.getHeight();

      // Footer background
      doc.setFillColor(...lightBg);
      doc.rect(0, finalPageHeight - 20, pageWidth, 20, 'F');

      // Footer border
      doc.setDrawColor(...primaryColor);
      doc.setLineWidth(1);
      doc.line(0, finalPageHeight - 20, pageWidth, finalPageHeight - 20);

      // Footer text
      doc.setFontSize(8);
      doc.setTextColor(...lightText);
      doc.text('Quiz Analytics Report - Confidential', 15, finalPageHeight - 12);
      doc.text(`Page ${i} of ${pageCount}`, pageWidth - 15, finalPageHeight - 12, {
        align: 'right'
      });
      doc.setFontSize(7);
      doc.text(`Generated on ${new Date().toLocaleDateString('en-IN')} by Learning Management System`, pageWidth / 2, finalPageHeight - 6, {
        align: 'center'
      });
    }

    // Save the PDF
    const filename = `admin-quiz-analytics-${reportType}-${new Date().toISOString().slice(0, 10)}.pdf`;
    doc.save(filename);
    return true;
  } catch (error) {
    console.error('Error generating admin quiz report PDF:', error);
    throw error;
  }
};

// Generate recommendations based on analytics data
function generateRecommendations(analyticsData) {
  const recommendations = [];
  const summary = analyticsData?.summary || {};

  // Pass rate recommendations
  if (summary.passRate < 60) {
    recommendations.push({
      priority: 'high',
      title: 'Low Overall Pass Rate Detected',
      description: `The current pass rate of ${(summary.passRate || 0).toFixed(1)}% is below the recommended 60% threshold. Consider reviewing quiz difficulty, providing additional study materials, or offering remedial sessions for struggling students.`
    });
  }

  // Average score recommendations
  if (summary.averageScore < 70) {
    recommendations.push({
      priority: 'high',
      title: 'Below Average Performance Scores',
      description: `The average score of ${(summary.averageScore || 0).toFixed(1)}% indicates students are struggling with the material. Review course content delivery, quiz alignment with learning objectives, and consider additional practice opportunities.`
    });
  }

  // Student engagement recommendations
  if (summary.uniqueStudents < 50) {
    recommendations.push({
      priority: 'medium',
      title: 'Low Student Engagement',
      description: `Only ${summary.uniqueStudents || 0} unique students have participated in quizzes. Implement engagement strategies such as gamification, regular reminders, and incentive programs to increase participation.`
    });
  }

  // Quiz difficulty recommendations
  if (analyticsData?.quizPerformance?.some(quiz => quiz.difficultyScore > 70)) {
    recommendations.push({
      priority: 'medium',
      title: 'High Difficulty Quizzes Identified',
      description: 'Several quizzes show high difficulty scores with low pass rates. Review these quizzes for clarity, appropriate difficulty level, and alignment with course materials.'
    });
  }

  // Student support recommendations
  if (analyticsData?.studentInsights?.strugglingStudents?.length > 10) {
    recommendations.push({
      priority: 'high',
      title: 'Multiple Students Need Support',
      description: `${analyticsData.studentInsights.strugglingStudents.length} students are showing poor performance. Implement targeted intervention strategies, one-on-one tutoring, or additional support resources.`
    });
  }

  // Default positive recommendation
  if (summary.passRate >= 80 && summary.averageScore >= 80) {
    recommendations.push({
      priority: 'low',
      title: 'Excellent Overall Performance',
      description: 'Students are performing well across all metrics. Continue current teaching methods and consider implementing advanced challenges or enrichment activities for high performers.'
    });
  }
  return recommendations.length > 0 ? recommendations : [{
    priority: 'low',
    title: 'Continue Monitoring',
    description: 'Performance metrics are within acceptable ranges. Continue regular monitoring and maintain current educational strategies.'
  }];
}
export default generateAdminQuizReportPDF;
